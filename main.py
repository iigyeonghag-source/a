def fit_font(draw, text, max_width, start=36):
    for size in range(start, 14, -2):
        font = get_font(size)

        bbox = draw.textbbox(
            (0, 0),
            text,
            font=font
        )

        width = bbox[2] - bbox[0]

        if width <= max_width:
            return font

    return get_font(14)

