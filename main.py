async def furina_auto(ctx, room):
    try:
        while room["started"] and current_player(room) == FURINA_ID:

            print("푸리나 턴 시작")

            # 이미 폴드/올인 상태면 다음 턴
            if (
                FURINA_ID in room["folded"]
                or FURINA_ID in room.get("all_in", set())
            ):
                room["turn_index"] = next_index(
                    room,
                    room["turn_index"]
                )
                continue

            need = room["current_bet"] - room["bets"].get(FURINA_ID, 0)

            strength = furina_hand_strength(room)
            pressure = is_big_pressure(room, need)

            print(
                f"need={need}, strength={strength:.2f}, pressure={pressure}"
            )

            # 상대가 이미 베팅한 경우
            if need > 0:
                decision = furina_decide_vs_bet(
                    strength,
                    pressure,
                    need
                )

                print("결정:", decision)

                if decision == "fold":
                    room["folded"].add(FURINA_ID)
                    room["acted"].add(FURINA_ID)

                    await ctx.send(
                        furina_say("furina_fold_weak")
                    )

                elif decision == "allin":
                    amount = choose_furina_raise_amount(
                        room,
                        strength,
                        all_in=True
                    )

                    pay = max(
                        0,
                        amount - room["bets"].get(FURINA_ID, 0)
                    )

                    room["current_bet"] = amount
                    room["bets"][FURINA_ID] = amount
                    room["pot"] += pay

                    room["acted"] = {FURINA_ID}
                    room.setdefault(
                        "all_in",
                        set()
                    ).add(FURINA_ID)

                    await ctx.send(
                        furina_say(
                            "furina_allin_call"
                        )
                    )

                else:  # call
                    room["pot"] += need
                    room["bets"][FURINA_ID] += need
                    room["acted"].add(FURINA_ID)

                    await ctx.send(
                        furina_say(
                            "furina_call",
                            need=need
                        )
                    )

            # 체크 상황
            else:
                decision = furina_decide_no_bet(
                    strength
                )

                print("결정:", decision)

                if decision == "allin":
                    amount = choose_furina_raise_amount(
                        room,
                        strength,
                        all_in=True
                    )

                    pay = max(
                        0,
                        amount - room["bets"].get(FURINA_ID, 0)
                    )

                    room["current_bet"] = amount
                    room["bets"][FURINA_ID] = amount
                    room["pot"] += pay

                    room["acted"] = {FURINA_ID}
                    room.setdefault(
                        "all_in",
                        set()
                    ).add(FURINA_ID)

                    await ctx.send(
                        furina_say(
                            "furina_allin_raise",
                            amount=amount
                        )
                    )

                elif decision in ("raise", "bluff"):
                    amount = choose_furina_raise_amount(
                        room,
                        strength
                    )

                    pay = max(
                        0,
                        amount - room["bets"].get(FURINA_ID, 0)
                    )

                    room["current_bet"] = amount
                    room["bets"][FURINA_ID] = amount
                    room["pot"] += pay

                    room["acted"] = {FURINA_ID}

                    await ctx.send(
                        furina_say(
                            "furina_bluff"
                            if decision == "bluff"
                            else "furina_raise",
                            amount=amount
                        )
                    )

                else:  # check
                    room["acted"].add(FURINA_ID)

                    await ctx.send(
                        furina_say("furina_check")
                    )

            # 승리 체크
            if len(active_players(room)) == 1:
                await win_by_fold(ctx, room)
                return

            # 라운드 종료
            if all_called(room):
                await advance_stage(ctx, room)
                return

            # 다음 턴
            room["turn_index"] = next_index(
                room,
                room["turn_index"]
            )

            await ctx.send(
                f"현재 턴: **{poker_name(ctx, current_player(room))}**"
            )

            # 푸리나 턴이면 연속 진행
            if current_player(room) != FURINA_ID:
                return

    except Exception as e:
        import traceback
        traceback.print_exc()

        await ctx.send(
            f"❌ 푸리나 AI 오류:\n```{e}```"
        )

