def get_favor(user_id):
    return favor.get(str(user_id), 0)

def add_favor(user_id, amount):
    uid = str(user_id)
    favor[uid] = favor.get(uid, 0) + amount
    favor[uid] = max(-100, min(100, favor[uid]))
    
    save_data()

def get_favor_stage(user_id):
    value = get_favor(user_id)

    if value >= 50:
        return "love"
    if value >= 10:
        return "friendly"
    if value <= -30:
        return "cold"
    return None

